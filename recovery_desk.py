"""
Recovery Desk: a prioritised vehicle-recovery queue for an auto lender's collections team.

Everything here runs on SYNTHETIC data generated by this script. No real borrower,
lender or vehicle data is used.

Run:  python recovery_desk.py
Output: data/vehicles_synthetic.csv, data/queue_today.csv, results.md
"""
import csv, math, random, statistics
from pathlib import Path

SEED = 7
N_VEHICLES = 500
AGENTS = 3
VISITS_PER_AGENT_DAY = 6
PILOT_DAYS = 10
random.seed(SEED)
Path("data").mkdir(exist_ok=True)


# ---------- 1. Synthetic portfolio (stands in for telematics + loan data) ----------
def make_vehicle(i):
    dpd = random.randint(31, 180)                         # days past due
    outstanding = round(random.uniform(1.2, 9.0), 2)      # Rs lakh still owed
    hours_since_ping = random.choice(                     # telematics freshness
        [random.uniform(0, 6)] * 6 + [random.uniform(6, 72)] * 3 + [random.uniform(72, 400)])
    km_last_7d = max(0.0, random.gauss(120, 110))
    night_parking_consistency = random.uniform(0, 1)      # share of nights at the same spot
    ignition_events_24h = random.randint(0, 12)
    # hidden "truth" used only to simulate outcomes, never shown to the ranking logic
    p_locate = (0.92 if hours_since_ping < 6 else 0.65 if hours_since_ping < 72 else 0.18)
    p_locate *= 0.55 + 0.45 * night_parking_consistency
    p_recover_given_found = 0.75 - 0.0015 * dpd - (0.15 if km_last_7d > 300 else 0)
    p_true = max(0.02, min(0.95, p_locate * p_recover_given_found + random.gauss(0, 0.05)))
    return dict(vehicle_id=f"V{i:04d}", days_past_due=dpd, outstanding_lakh=outstanding,
                hours_since_last_ping=round(hours_since_ping, 1), km_last_7d=round(km_last_7d, 1),
                night_parking_consistency=round(night_parking_consistency, 2),
                ignition_events_24h=ignition_events_24h, _p_true=p_true)

fleet = [make_vehicle(i) for i in range(1, N_VEHICLES + 1)]
with open("data/vehicles_synthetic.csv", "w", newline="") as f:
    cols = [k for k in fleet[0] if not k.startswith("_")]
    w = csv.DictWriter(f, fieldnames=cols); w.writeheader()
    for v in fleet: w.writerow({k: v[k] for k in cols})


# ---------- 2. Recovery Desk score: only uses signals an ops team would actually see ----------
def score(v):
    fresh = math.exp(-v["hours_since_last_ping"] / 48)              # recent ping = findable
    parked = 0.4 + 0.6 * v["night_parking_consistency"]             # predictable location
    mobile_penalty = 0.75 if v["km_last_7d"] > 300 else 1.0         # very mobile = harder
    age_penalty = 1 - 0.002 * v["days_past_due"]                    # older dues recover less
    p_hat = fresh * parked * mobile_penalty * age_penalty
    return p_hat, p_hat * v["outstanding_lakh"]                     # expected Rs lakh recovered


def brief(v, p_hat):
    """Agent brief. Rule-based here; the next version swaps this for an LLM call."""
    why = []
    if v["hours_since_last_ping"] < 6: why.append("vehicle pinged in the last 6 hours")
    if v["night_parking_consistency"] > 0.7: why.append("parks at the same spot most nights")
    if v["km_last_7d"] > 300: why.append("high movement this week, plan a quick visit")
    if v["hours_since_last_ping"] > 72: why.append("GPS dark for 3+ days, verify device status first")
    action = ("Visit between 8 am and 7 pm at the usual night location; carry loan documents."
              if p_hat > 0.35 else "Call first to confirm location; do not visit blind.")
    return f"{v['vehicle_id']}: Rs {v['outstanding_lakh']} lakh, {v['days_past_due']} DPD. " \
           f"Why now: {'; '.join(why) or 'no strong signal'}. Next step: {action}"


for v in fleet:
    v["p_hat"], v["exp_value"] = score(v)


# ---------- 3. Simulated pilot: Recovery Desk queue vs today's oldest-dues-first queue ----------
def simulate(order_key, reverse, label):
    rng = random.Random(SEED)
    pool = sorted(fleet, key=order_key, reverse=reverse)
    recovered_value, recovered_count, visits = 0.0, 0, 0
    capacity = AGENTS * VISITS_PER_AGENT_DAY
    for _ in range(PILOT_DAYS):
        today, pool = pool[:capacity], pool[capacity:]
        for v in today:
            visits += 1
            if rng.random() < v["_p_true"]:
                recovered_value += v["outstanding_lakh"]; recovered_count += 1
    agent_days = AGENTS * PILOT_DAYS
    return dict(label=label, visits=visits, recovered=recovered_count,
                hit_rate=recovered_count / visits, value_lakh=recovered_value,
                per_agent_day=recovered_value / agent_days)

baseline = simulate(lambda v: v["days_past_due"], True, "Oldest dues first (status quo)")
desk = simulate(lambda v: v["exp_value"], True, "Recovery Desk ranking")

with open("data/queue_today.csv", "w", newline="") as f:
    w = csv.writer(f); w.writerow(["rank", "vehicle_id", "expected_value_lakh", "agent_brief"])
    top = sorted(fleet, key=lambda v: v["exp_value"], reverse=True)[:AGENTS * VISITS_PER_AGENT_DAY]
    for r, v in enumerate(top, 1):
        w.writerow([r, v["vehicle_id"], round(v["exp_value"], 2), brief(v, v["p_hat"])])

lift = desk["per_agent_day"] / baseline["per_agent_day"] - 1
lines = ["# Simulated pilot results (synthetic data)", "",
         f"{N_VEHICLES} delinquent vehicles, {AGENTS} agents x {VISITS_PER_AGENT_DAY} visits/day, {PILOT_DAYS} days.", "",
         "| Queue | Visits | Vehicles recovered | Hit rate | Rs lakh recovered | Rs lakh per agent-day |",
         "|---|---|---|---|---|---|"]
for r in (baseline, desk):
    lines.append(f"| {r['label']} | {r['visits']} | {r['recovered']} | {r['hit_rate']:.0%} | "
                 f"{r['value_lakh']:.1f} | {r['per_agent_day']:.2f} |")
lines += ["", f"North-star lift: **{lift:+.0%} Rs recovered per agent-day** versus the status quo.", "",
          "Sample agent briefs for today's top 3:", ""]
for v in sorted(fleet, key=lambda v: v["exp_value"], reverse=True)[:3]:
    lines.append(f"- {brief(v, v['p_hat'])}")
Path("results.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
